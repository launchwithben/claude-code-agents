#!/usr/bin/env bash
# build_skills.sh - generate rules skills FROM the project's docs, so they cannot drift.
# A hand-copied SKILL.md goes stale the day its source doc changes; here the skill is a build product of the doc
# section(s) named in the skills file, and --check fails when a committed SKILL.md differs from what this would write.
#
# Skills file (roles.config.json "skills", default roles/skills.txt), one skill per line:
#   <skill-name> | <description> | <doc>#<## heading prefix> [; <doc>#<heading>]... [| <key: value> [; <key: value>]...]
# The optional 4th column declares more frontmatter, written after `description:` in order, e.g.
#   acme-lead-rules | Lead rules | docs/lead.md#Rules | user-invocable: true
# A section is the "## <prefix>..." heading up to the next "## " heading, read from <doc> (relative to the root).
#
# Usage: build_skills.sh          write .claude/skills/<name>/SKILL.md for every line
#        build_skills.sh --check  exit 1 (and name the skill) if any committed SKILL.md is stale
# Root: $ROLE_KIT_ROOT, else $CLAUDE_PROJECT_DIR, else the current directory. Skills file: $ROLE_KIT_SKILLS_FILE overrides.
set -uo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "${ROLE_KIT_ROOT:-${CLAUDE_PROJECT_DIR:-$PWD}}" && pwd)"
CHECK=0; [[ "${1:-}" == "--check" ]] && CHECK=1
rel="${ROLE_KIT_SKILLS_FILE:-$(python3 "$here/../hooks/_kit.py" cfg "$ROOT" skills roles/skills.txt)}"
[[ -z "$rel" ]] && rel="roles/skills.txt"
file="$ROOT/$rel"; [[ "$rel" == /* ]] && file="$rel"
if [[ ! -f "$file" ]]; then echo "build_skills: no skills file at $file (nothing to build)"; exit 0; fi
stale=0
section() {   # section <doc> <heading prefix>
  awk -v h="## $2" 'index($0,h)==1{on=1;print;next} on&&/^## /{exit} on' "$ROOT/$1"
}
trim() { sed 's/^[[:space:]]*//; s/[[:space:]]*$//' <<<"$1"; }
while IFS='|' read -r name desc srcs fm; do
  name="$(trim "$name")"; desc="$(trim "$desc")"
  [[ -z "$name" || "$name" == \#* ]] && continue
  body=""
  IFS=';' read -ra parts <<<"$srcs"
  for p in "${parts[@]}"; do
    p="$(trim "$p")"; doc="${p%%#*}"; head="${p#*#}"
    [[ -f "$ROOT/$doc" ]] || { echo "build_skills: '$name': no such doc $doc" >&2; exit 1; }
    s="$(section "$doc" "$head")"
    [[ -n "$s" ]] || { echo "build_skills: '$name': no '## $head' section in $doc" >&2; exit 1; }
    body+=$'\n'"<!-- source: $doc § $head -->"$'\n'"$s"$'\n'
  done
  extra=""
  if [[ -n "$(trim "$fm")" ]]; then
    IFS=';' read -ra fmparts <<<"$fm"
    for kv in "${fmparts[@]}"; do kv="$(trim "$kv")"; [[ -n "$kv" ]] && extra+=$'\n'"$kv"; done
  fi
  out="---
name: $name
description: $desc$extra
---
<!-- GENERATED by build_skills.sh from the sources named below. Do not edit: change the doc, then re-run the script. -->
$body"
  f="$ROOT/.claude/skills/$name/SKILL.md"
  if (( CHECK )); then
    [[ -f "$f" && "$(cat "$f")" == "$(printf '%s\n' "$out")" ]] || { echo "STALE: $f (run build_skills.sh)"; stale=1; }
  else
    mkdir -p "$(dirname "$f")"; printf '%s\n' "$out" > "$f"; echo "wrote $f"
  fi
done < "$file"
exit $stale
